import { mkdir, readdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
const root = resolve('.artifacts/android-ime-fixture');
const source = resolve('tests/android-ime-fixture');
const sdk = process.env.ANDROID_HOME ?? 'C:/AndroidSDK';
const java = process.env.JAVA_HOME ?? 'C:/Program Files/Java/jdk-17.0.2';
const build = `${sdk}/build-tools/36.0.0`;
const run = (file, args) => execFileSync(file, args, { stdio: 'inherit', windowsHide: true });
await mkdir(`${root}/classes`, { recursive: true });
await mkdir(`${root}/dex`, { recursive: true });
run(`${java}/bin/javac.exe`, ['-encoding','UTF-8','-source','8','-target','8','-classpath',`${sdk}/platforms/android-36/android.jar`,'-d',`${root}/classes`,`${source}/FixtureActivity.java`,`${source}/FixtureIme.java`]);
const classes = (await readdir(`${root}/classes/app/familiar/imefixture`)).filter(n => n.endsWith('.class')).map(n => `${root}/classes/app/familiar/imefixture/${n}`);
run(`${java}/bin/java.exe`, ['-cp',`${build}/lib/d8.jar`,'com.android.tools.r8.D8','--lib',`${sdk}/platforms/android-36/android.jar`,'--min-api','28','--output',`${root}/dex`,...classes]);
run(`${build}/aapt2.exe`, ['compile','--dir',`${source}/res`,'-o',`${root}/res.zip`]);
run(`${build}/aapt2.exe`, ['link','-I',`${sdk}/platforms/android-36/android.jar`,'--manifest',`${source}/AndroidManifest.xml`,'-o',`${root}/unsigned.apk`,`${root}/res.zip`]);
run(`${java}/bin/jar.exe`, ['uf',`${root}/unsigned.apk`,'-C',`${root}/dex`,'classes.dex']);
run(`${build}/zipalign.exe`, ['-f','4',`${root}/unsigned.apk`,`${root}/aligned.apk`]);
run(`${java}/bin/java.exe`, ['-jar',`${build}/lib/apksigner.jar`,'sign','--ks',`${process.env.USERPROFILE}/.android/debug.keystore`,'--ks-pass','pass:android','--out',`${root}/fixture.apk`,`${root}/aligned.apk`]);
console.log(`${root}/fixture.apk`);
